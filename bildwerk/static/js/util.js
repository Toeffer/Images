export function icon(name, className = 'icon') {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('class', className);
  svg.setAttribute('aria-hidden', 'true');
  svg.innerHTML = ICONS[name] || ICONS.info;
  return svg;
}

export function hydrateIcons(root = document) {
  for (const node of $$('[data-icon]', root)) {
    if (!node.firstElementChild) node.append(icon(node.dataset.icon));
  }
}

export function toast(message, type = 'info', timeout = 5000) {
  const box = $('#toasts');
  const close = () => item.remove();
  const item = el('div', { class: `toast ${type}`, role: type === 'error' ? 'alert' : 'status' },
    el('span', { class: 'toast-text' }, message),
    el('button', { title: 'Schließen', onclick: close }, icon('x')));
  box.append(item);
  if (timeout) setTimeout(close, type === 'error' ? Math.max(timeout, 8000) : timeout);
  return item;
}

export function errorMessage(err) {
  if (err?.name === 'AbortError') return null;
  if (err instanceof TypeError) return 'Keine Verbindung zu Bildwerk. Läuft das Programm noch?';
  return err?.message || String(err);
}

export function showError(err) {
  const message = errorMessage(err);
  if (message) toast(message, 'error');
}

export function debounce(fn, ms) {
  let timer = null;
  const wrapped = (...args) => {
    clearTimeout(timer);
    timer = setTimeout(() => fn(...args), ms);
  };
  wrapped.cancel = () => clearTimeout(timer);
  return wrapped;
}

export const clamp = (v, lo, hi) => Math.min(hi, Math.max(lo, v));

export function formatNumber(value, step) {
  const decimals = step && step < 1 ? Math.min(2, String(step).split('.')[1]?.length || 1) : 0;
  return Number(value).toLocaleString('de-DE', { minimumFractionDigits: decimals, maximumFractionDigits: decimals });
}

export const storage = {
  get(key, fallback = null) {
    try {
      const raw = localStorage.getItem(`bildwerk.${key}`);
      return raw == null ? fallback : JSON.parse(raw);
    } catch {
      return fallback;
    }
  },
  set(key, value) {
    try {
      localStorage.setItem(`bildwerk.${key}`, JSON.stringify(value));
    } catch {
      /* z. B. privater Modus – dann eben ohne Merken */
    }
  },
};

const NON_TEXT_INPUTS = ['range', 'checkbox', 'radio', 'color', 'button', 'submit', 'file'];

/** True, wenn gerade Text eingegeben wird – dann gelten keine Tastenkürzel. */
export function isTyping(event) {
  const t = event.target;
  if (!(t instanceof HTMLElement)) return false;
  if (t.tagName === 'INPUT') return !NON_TEXT_INPUTS.includes(t.type);
  return t.isContentEditable || t.tagName === 'TEXTAREA' || t.tagName === 'SELECT';
}
